/**
 * Builds src/lib/blog/image-manifest.js from the files in static/images/blog/.
 *
 * Blog posts reference images by URL ("/images/blog/foo.jpg"). Reading each
 * image's real dimensions at build time lets the markdown pipeline emit
 * width/height attributes, which is what stops images from shifting the page
 * as they load. Runs automatically before `dev` and `build`, or on demand:
 *
 *   node scripts/generate-image-manifest.mjs
 */
import { readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

let sharp;
try {
	({ default: sharp } = await import('sharp'));
} catch (error) {
	// This runs before every `dev` and `build`. If sharp is unavailable (its
	// install script is skipped in some environments), keep the committed
	// manifest rather than blocking the build — images just lose their
	// reserved dimensions until it is regenerated.
	console.warn(`Image manifest not regenerated: ${error.message}`);
	process.exit(0);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const imageDir = join(root, 'static/images/blog');
const target = join(root, 'src/lib/blog/image-manifest.js');
const IMAGE_RE = /\.(avif|gif|jpe?g|png|svg|webp)$/i;

/** @param {string} dir @returns {Promise<string[]>} */
async function listImages(dir) {
	let entries;
	try {
		entries = await readdir(dir, { withFileTypes: true });
	} catch (error) {
		if (error.code === 'ENOENT') return [];
		throw error;
	}

	const found = await Promise.all(
		entries.map((entry) => {
			const full = join(dir, entry.name);
			if (entry.isDirectory()) return listImages(full);
			return IMAGE_RE.test(entry.name) ? [full] : [];
		})
	);

	return found.flat();
}

const files = (await listImages(imageDir)).sort();
const manifest = {};

for (const file of files) {
	const { width, height, format } = await sharp(file).metadata();
	if (!width || !height) {
		console.warn(`skipped (no dimensions): ${file}`);
		continue;
	}
	const url = '/images/blog/' + relative(imageDir, file).split(sep).join('/');
	manifest[url] = { width, height, format };
}

const body = `// AUTO-GENERATED by scripts/generate-image-manifest.mjs — do not edit by hand.
// Intrinsic dimensions of every image in static/images/blog, keyed by URL.
export const imageManifest = ${JSON.stringify(manifest, null, '\t')};

/** Look up an image's intrinsic size, or undefined when it is unknown/remote. */
export function getImageMeta(src) {
	if (!src) return undefined;
	return imageManifest[src.split(/[?#]/)[0]] ?? undefined;
}

export default imageManifest;
`;

await writeFile(target, body, 'utf8');
console.log(`Wrote ${Object.keys(manifest).length} entries to src/lib/blog/image-manifest.js`);
